import io
import csv
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from models import Alert, Incident, PrioritizationResult

class ReportService:
    def export_csv(self, alerts_query=None):
        """Generate CSV string of alerts with priority and risk scoring."""
        output = io.StringIO()
        writer = csv.writer(output)

        writer.writerow([
            'Alert ID', 'Timestamp', 'Title', 'Attack Type', 'Source IP', 'Destination IP',
            'Asset Name', 'Asset Criticality', 'Raw Severity', 'Risk Score', 'Priority Level',
            'ML Prediction', 'ML Confidence (%)', 'Threat Intel Score', 'MITRE Technique',
            'Status', 'Recommended Action'
        ])

        if alerts_query is None:
            alerts = Alert.query.order_by(Alert.timestamp.desc()).all()
        else:
            alerts = alerts_query.all()

        for a in alerts:
            p = a.prioritization
            writer.writerow([
                a.alert_id,
                a.timestamp.strftime('%Y-%m-%d %H:%M:%S') if a.timestamp else '',
                a.title,
                a.attack_type,
                a.source_ip,
                a.destination_ip,
                a.asset_name,
                a.asset_criticality,
                a.raw_severity,
                p.risk_score if p else '',
                p.priority_level if p else '',
                p.ml_priority if p else '',
                p.ml_confidence if p else '',
                p.threat_intel_score if p else '',
                f"{a.mitre_technique_id} ({a.mitre_technique_name})" if a.mitre_technique_id else '',
                a.status,
                p.recommended_action if p else ''
            ])

        return output.getvalue()

    def export_pdf(self, title="SOC Executive Security & Threat Intelligence Report"):
        """
        Generate enterprise-grade cybersecurity PDF report using ReportLab.
        """
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )

        styles = getSampleStyleSheet()

        # Custom styles
        title_style = ParagraphStyle(
            'CyberTitle',
            parent=styles['Heading1'],
            fontSize=20,
            leading=24,
            textColor=colors.HexColor('#0f172a'),
            fontName='Helvetica-Bold'
        )
        subtitle_style = ParagraphStyle(
            'CyberSubTitle',
            parent=styles['Normal'],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor('#64748b'),
            fontName='Helvetica'
        )
        section_style = ParagraphStyle(
            'CyberSection',
            parent=styles['Heading2'],
            fontSize=13,
            leading=16,
            textColor=colors.HexColor('#1e293b'),
            fontName='Helvetica-Bold',
            spaceBefore=12,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            'CyberBody',
            parent=styles['Normal'],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor('#334155'),
            fontName='Helvetica'
        )
        cell_style = ParagraphStyle(
            'CyberCell',
            parent=styles['Normal'],
            fontSize=8,
            leading=10,
            textColor=colors.HexColor('#1e293b'),
            fontName='Helvetica'
        )
        cell_bold = ParagraphStyle(
            'CyberCellBold',
            parent=cell_style,
            fontName='Helvetica-Bold'
        )

        elements = []

        # Header Title
        elements.append(Paragraph(title, title_style))
        gen_time = datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')
        elements.append(Paragraph(f"Generated by SOC Alert Prioritization Engine | Classification: TLP:AMBER | Date: {gen_time}", subtitle_style))
        elements.append(Spacer(1, 10))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#0284c7'), spaceAfter=14))

        # Metrics Summary Calculation
        total_alerts = Alert.query.count()
        critical_count = PrioritizationResult.query.filter_by(priority_level='Critical').count()
        high_count = PrioritizationResult.query.filter_by(priority_level='High').count()
        med_count = PrioritizationResult.query.filter_by(priority_level='Medium').count()
        low_count = PrioritizationResult.query.filter_by(priority_level='Low').count()
        active_incidents = Incident.query.filter(Incident.status.in_(['Open', 'In Progress', 'Contained'])).count()
        resolved_incidents = Incident.query.filter_by(status='Resolved').count()

        elements.append(Paragraph("1. Executive Summary & Alert Prioritization Metrics", section_style))
        
        summary_data = [
            [
                Paragraph('<b>Total Ingested Alerts</b>', cell_style),
                Paragraph(str(total_alerts), cell_bold),
                Paragraph('<b>Active Incidents</b>', cell_style),
                Paragraph(str(active_incidents), cell_bold)
            ],
            [
                Paragraph('<b>Critical Priority (AI)</b>', cell_style),
                Paragraph(f"<font color='#dc2626'><b>{critical_count}</b></font>", cell_style),
                Paragraph('<b>High Priority (AI)</b>', cell_style),
                Paragraph(f"<font color='#ea580c'><b>{high_count}</b></font>", cell_style)
            ],
            [
                Paragraph('<b>Medium Priority</b>', cell_style),
                Paragraph(f"<font color='#ca8a04'><b>{med_count}</b></font>", cell_style),
                Paragraph('<b>Low / Benign Noise</b>', cell_style),
                Paragraph(f"<font color='#16a34a'><b>{low_count}</b></font>", cell_style)
            ],
            [
                Paragraph('<b>Resolved Incidents</b>', cell_style),
                Paragraph(str(resolved_incidents), cell_bold),
                Paragraph('<b>Noise Reduction Rate</b>', cell_style),
                Paragraph(f"{round((low_count / max(1, total_alerts)) * 100, 1)}%", cell_bold)
            ]
        ]

        summary_table = Table(summary_data, colWidths=[1.8*inch, 1.2*inch, 1.8*inch, 1.2*inch])
        summary_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#f8fafc')),
            ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#cbd5e1')),
            ('TOPPADDING', (0,0), (-1,-1), 5),
            ('BOTTOMPADDING', (0,0), (-1,-1), 5),
        ]))
        elements.append(summary_table)
        elements.append(Spacer(1, 14))

        # Section 2: Top Critical Threats Requiring Urgent Action
        elements.append(Paragraph("2. Prioritized Critical Alerts & Threat Intelligence Findings", section_style))
        
        crit_alerts = Alert.query.join(PrioritizationResult).filter(
            PrioritizationResult.priority_level == 'Critical'
        ).order_by(PrioritizationResult.risk_score.desc()).limit(8).all()

        if crit_alerts:
            alert_table_data = [[
                Paragraph('<b>Alert ID</b>', cell_bold),
                Paragraph('<b>Attack Type</b>', cell_bold),
                Paragraph('<b>Source IP</b>', cell_bold),
                Paragraph('<b>Target Asset</b>', cell_bold),
                Paragraph('<b>Risk</b>', cell_bold),
                Paragraph('<b>MITRE</b>', cell_bold),
                Paragraph('<b>Recommended Response Action</b>', cell_bold)
            ]]

            for a in crit_alerts:
                p = a.prioritization
                alert_table_data.append([
                    Paragraph(a.alert_id, cell_style),
                    Paragraph(a.attack_type, cell_style),
                    Paragraph(a.source_ip, cell_style),
                    Paragraph(a.asset_name, cell_style),
                    Paragraph(f"<b>{p.risk_score}</b>", cell_style),
                    Paragraph(a.mitre_technique_id or 'N/A', cell_style),
                    Paragraph(p.recommended_action[:90] + '...' if len(p.recommended_action) > 90 else p.recommended_action, cell_style)
                ])

            alert_table = Table(alert_table_data, colWidths=[0.8*inch, 1.0*inch, 0.9*inch, 1.0*inch, 0.5*inch, 0.6*inch, 2.2*inch])
            alert_table.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#fee2e2')),
                ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#fca5a5')),
                ('TOPPADDING', (0,0), (-1,-1), 4),
                ('BOTTOMPADDING', (0,0), (-1,-1), 4),
            ]))
            elements.append(alert_table)
        else:
            elements.append(Paragraph("No critical threats currently active.", body_style))

        elements.append(Spacer(1, 14))

        # Section 3: Strategic Recommendations
        elements.append(Paragraph("3. Strategic Recommendations for SOC Analysts & Management", section_style))
        recs = [
            "1. <b>Automate Firewall Blocking</b>: Offending IPs flagged by Threat Intelligence with reputation scores > 90 should be automatically fed to boundary firewalls.",
            "2. <b>Host Isolation Playbooks</b>: Ensure EDR agents on Crown Jewel assets have automatic network isolation enabled for active C2 beaconing alerts.",
            "3. <b>MFA Enforcement</b>: High volumes of Brute Force attempts against RDP/SSH indicate unpatched external bastions; enforce hardware MFA keys and Geo-IP filtering.",
            "4. <b>Model Feedback Loop</b>: Analysts should mark false positives regularly to continually refine the machine learning prioritization weights."
        ]
        for r in recs:
            elements.append(Paragraph(r, body_style))
            elements.append(Spacer(1, 4))

        doc.build(elements)
        buffer.seek(0)
        return buffer.getvalue()
